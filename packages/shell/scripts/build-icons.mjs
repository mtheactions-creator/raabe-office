// Generates src/icons.gen.ts from scripts/icons.json: for each icon a small (20 px) and a
// large (32 px, or the largest available) SVG from Fluent UI System Icons (MIT licence).
// Only the icons we use end up in the app.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const iconDir = join(dirname(require.resolve("@fluentui/svg-icons/package.json")), "icons");
const map = JSON.parse(readFileSync(join(here, "icons.json"), "utf8"));

function load(base, sizes) {
  for (const s of sizes) {
    const file = join(iconDir, `${base}_${s}_regular.svg`);
    if (existsSync(file)) {
      return readFileSync(file, "utf8")
        .replace(/\s(width|height)="\d+"/g, "")
        .replace(/fill="[^"]*"/g, 'fill="currentColor"')
        .replace("<svg", '<svg aria-hidden="true" focusable="false"')
        .trim();
    }
  }
  return null;
}

const missing = [];
const lines = [];
for (const [name, base] of Object.entries(map)) {
  if (name.startsWith("_")) continue;
  const small = load(base, [20, 16, 24]);
  const large = load(base, [32, 28, 24, 20]);
  if (!small || !large) { missing.push(`${name} -> ${base}`); continue; }
  lines.push(`  ${JSON.stringify(name)}: { s: ${JSON.stringify(small)}, l: ${JSON.stringify(large)} },`);
}
if (missing.length) {
  console.error("Missing Fluent icons:\n  " + missing.join("\n  "));
  process.exit(1);
}
const out = `// Generated by scripts/build-icons.mjs from Fluent UI System Icons (MIT). Do not edit.
// https://github.com/microsoft/fluentui-system-icons

export const ICONS: Record<string, { s: string; l: string }> = {
${lines.join("\n")}
};
`;
writeFileSync(join(here, "..", "src", "icons.gen.ts"), out);
console.log(`icons.gen.ts: ${lines.length} icons`);
