// Generates apps/raabe-write/src/features/math-gallery.ts: what every entry of Word's equation
// galleries inserts (tools/feel-lab/probe_word_equation_gallery.py writes Word's OMML to the
// local captures/word-equation/gallery.json), read with our OMML reader and stored as trees,
// with the galleries' headings and tile sizes (results/<date>-word-equation-ui.json).
//
//   GEN_MATH_GALLERY=1 npx vitest run packages/ooxml/test/gen-math-gallery.test.ts

import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { implode, type Seq } from "@raabe/text-engine";
import { ommlToSeq } from "../src/math";

const LAB = join(__dirname, "..", "..", "..", "tools", "feel-lab");
const SOURCE = join(LAB, "captures", "word-equation", "gallery.json");
const OUT = join(__dirname, "..", "..", "..", "apps", "raabe-write", "src", "features", "math-gallery.ts");
const M_NS = "http://schemas.openxmlformats.org/officeDocument/2006/math";
const W_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main";

/** The ribbon command of each of Word's structure galleries. */
const COMMANDS: Record<string, string> = {
  Bruch: "math.fraction", "Hoch/Tief": "math.script", Wurzel: "math.radical", Integral: "math.integral", "Großer Operator": "math.nary",
  "Eckige Klammer": "math.bracket", Funktion: "math.function", Akzent: "math.accent", "Grenzwert und Logarithmus": "math.limit",
  Operator: "math.operator", Matrix: "math.matrix",
};

/** Word's math italic letters (𝑥, 𝜃 …, as Range.Text reports them) as the letters they stand for. */
function plainLetters(s: string): string {
  // After the small letters of the italic Greek block: ∂ ϵ ϑ ϰ ϕ ϱ ϖ.
  const greekTail = [0x2202, 0x3f5, 0x3d1, 0x3f0, 0x3d5, 0x3f1, 0x3d6];
  return [...s].map((c) => {
    const cp = c.codePointAt(0)!;
    if (cp >= 0x1d434 && cp <= 0x1d467) { const k = cp - 0x1d434; return String.fromCharCode(k < 26 ? 65 + k : 97 + k - 26); }
    if (cp === 0x210e) return "h";
    if (cp >= 0x1d6e2 && cp <= 0x1d6fa) { const k = cp - 0x1d6e2; return String.fromCharCode(k === 17 ? 0x3f4 : 0x391 + k); }
    if (cp === 0x1d6fb) return "∇";
    if (cp >= 0x1d6fc && cp <= 0x1d714) return String.fromCharCode(0x3b1 + cp - 0x1d6fc);
    if (cp >= 0x1d715 && cp <= 0x1d71b) return String.fromCharCode(greekTail[cp - 0x1d715]);
    return c;
  }).join("");
}

function seqOf(omml: string): Seq | null {
  const doc = new DOMParser().parseFromString(`<r xmlns:m="${M_NS}" xmlns:w="${W_NS}">${omml}</r>`, "application/xml");
  const maths = Array.from(doc.getElementsByTagNameNS(M_NS, "oMath"));
  if (!maths.length) return null;
  const parts: Seq = [];
  maths.forEach((m, i) => {
    const s = ommlToSeq(m);
    if (s) { if (i) parts.push({ k: "t", s: "\n" }); parts.push(...s); }
  });
  return implode(parts);
}

const strip = (label: string) => label.replace(/^Formel(struktur|symbol) /, "").trim();
const js = (s: string) => JSON.stringify(s);

describe.runIf(!!process.env.GEN_MATH_GALLERY && existsSync(SOURCE))("generate math-gallery.ts", () => {
  it("writes the galleries", () => {
    const src = JSON.parse(readFileSync(SOURCE, "utf-8")) as Record<string, unknown>;
    const ui = readdirSync(join(LAB, "results")).filter((f) => f.endsWith("-word-equation-ui.json")).sort().pop()!;
    const popups = (JSON.parse(readFileSync(join(LAB, "results", ui), "utf-8")) as { popups: Record<string, { type: string; name: string; rect: number[] }[]> }).popups;
    const problems: string[] = [];

    const entry = (e: { label: string; omml?: string; error?: string }) => {
      if (!e.omml) { problems.push(`${e.label}: ${e.error ?? "no OMML"}`); return null; }
      const seq = seqOf(e.omml);
      if (!seq) { problems.push(`${e.label}: unreadable`); return null; }
      return { label: strip(e.label), seq: JSON.stringify(seq) };
    };

    /** Tile size of each entry in Word's popup, in order, and the popup's width (CSS px at 150 %). */
    const px = (v: number) => Math.round(v / 1.5);
    const tiles = (gallery: string) => (popups[gallery] ?? []).filter((x) => x.type === "ListItem").map((x) => [px(x.rect[2]), px(x.rect[3])] as [number, number]);
    const widthOf = (gallery: string) => { const m = (popups[gallery] ?? []).find((x) => x.type === "Menu"); return m ? px(m.rect[2]) : 340; };

    const lines: string[] = [
      "// Generated by packages/ooxml/test/gen-math-gallery.test.ts from what Word's equation galleries",
      "// insert (tools/feel-lab/probe_word_equation_gallery.py). Do not edit.",
      "",
      "import type { Seq } from \"@raabe/text-engine\";",
      "",
      "/** An entry; `size` is its tile in Word's popup when it differs from the group's. */",
      "export interface GalleryItem { label: string; seq: Seq; size?: [number, number] }",
      "export interface GalleryGroup { heading: string; tile: [number, number]; items: GalleryItem[] }",
      "",
    ];
    // Integriert (Einfügen > Formel, Formel > Formel).
    const builtIn = (src.Formel as { heading: string; label: string; omml?: string }[]).filter((e) => e.heading === "Integriert");
    lines.push("/** Word's built-in equations (Einfügen > Formel). */", "export const BUILT_IN: { name: string; seq: Seq }[] = [");
    for (const e of builtIn) { const x = entry(e); if (x) lines.push(`  { name: ${js(x.label)}, seq: ${x.seq} },`); }
    lines.push("];", "");
    // The structure galleries.
    lines.push("/** Formel > Strukturen: each gallery's headings and entries. */", "export const MATH_GALLERIES: Record<string, GalleryGroup[]> = {");
    const widths: string[] = [];
    for (const [gallery, id] of Object.entries(COMMANDS)) {
      const list = src[gallery] as { heading: string; label: string; omml?: string }[] | undefined;
      if (!list) { problems.push(`${gallery}: not recorded`); continue; }
      const sizes = tiles(gallery);
      if (sizes.length !== list.length) problems.push(`${gallery}: ${sizes.length} tiles for ${list.length} entries`);
      widths.push(`  ${js(id)}: ${widthOf(gallery)},`);
      lines.push(`  ${js(id)}: [`);
      const groups = new Map<string, { tile: [number, number]; items: string[] }>();
      list.forEach((e, k) => {
        const x = entry(e);
        if (!x) return;
        const size = sizes[k] ?? [80, 104];
        if (!groups.has(e.heading)) groups.set(e.heading, { tile: size, items: [] });
        const g = groups.get(e.heading)!;
        const own = size[0] !== g.tile[0] || size[1] !== g.tile[1] ? `, size: [${size[0]}, ${size[1]}]` : "";
        g.items.push(`      { label: ${js(x.label)}, seq: ${x.seq}${own} },`);
      });
      for (const [heading, g] of groups) lines.push(`    { heading: ${js(heading)}, tile: [${g.tile[0]}, ${g.tile[1]}], items: [`, ...g.items, "    ] },");
      lines.push("  ],");
    }
    lines.push("};", "", "/** The width of each gallery's popup in Word (CSS px). */", "export const MATH_GALLERY_WIDTHS: Record<string, number> = {", ...widths, "};", "");
    // Formelsymbole: the categories and their characters.
    const symbols = (src.symbols ?? {}) as Record<string, { heading: string; label: string; text?: string }[]>;
    lines.push("/** Formel > Symbole: Word's categories, their headings and symbols ([character, name]). */",
      "export const SYMBOL_CATEGORIES: { name: string; groups: { heading: string; items: [string, string][] }[] }[] = [");
    // Word's order of the categories (Katalogfilter).
    const ORDER = ["Grundlegende Mathematik", "Griechische Buchstaben", "Buchstabenähnliche Symbole", "Operatoren", "Pfeile", "Negierte Beziehungen", "Schreibschriften", "Geometrie"];
    const cats = Object.entries(symbols).sort((a, b) => ORDER.indexOf(a[0]) - ORDER.indexOf(b[0]));
    for (const [cat, all] of cats) {
      lines.push(`  { name: ${js(cat)}, groups: [`);
      const groups = new Map<string, string[]>();
      // The probe lists the ribbon's gallery (characters) and then the panel (headings).
      const half = all.length / 2;
      const paired = Number.isInteger(half) && all.slice(0, half).every((e, i) => e.label === all[half + i].label);
      const list = paired ? all.slice(0, half).map((e, i) => ({ ...e, heading: all[half + i].heading })) : all;
      for (const e of list) {
        const ch = plainLetters((e.text ?? "").replace(/[\r\n]/g, ""));
        if (!ch) { problems.push(`${cat} ${e.label}: no character`); continue; }
        if (!groups.has(e.heading)) groups.set(e.heading, []);
        groups.get(e.heading)!.push(`[${js(ch)}, ${js(strip(e.label))}]`);
      }
      for (const [heading, items] of groups) lines.push(`    { heading: ${js(heading === cat ? "" : heading)}, items: [${items.join(", ")}] },`);
      lines.push("  ] },");
    }
    lines.push("];", "");
    writeFileSync(OUT, lines.join("\n"), "utf-8");
    console.log(problems.join("\n") || "no problems");
    expect(builtIn.length).toBeGreaterThan(0);
  });
});
