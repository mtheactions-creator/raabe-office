// Generates apps/raabe-write/src/features/text-effects.gen.ts: what Word's Texteffekte und
// Typografie menu applies (tools/feel-lab/probe_word_texteffects.py applied each entry in Word
// and recorded the run's XML: results/<date>-word-texteffects.json). Presets keep their font
// colour (w:color) and w14 elements; the Schatten, Spiegelung and Leuchten entries their one
// element.
//
//   GEN_TEXTFX=1 npx vitest run packages/ooxml/test/gen-textfx.test.ts

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

const RESULTS = join(__dirname, "..", "..", "..", "tools", "feel-lab", "results");
const OUT = join(__dirname, "..", "..", "..", "apps", "raabe-write", "src", "features", "text-effects.gen.ts");

const strip = (xml: string) => xml.replace(/ xmlns:w14="[^"]*"/g, "");
const w14 = (xml: string, name: string) => new RegExp(`<w14:${name}\\b[^>]*?(?:/>|>[\\s\\S]*?</w14:${name}>)`).exec(xml)?.[0];

describe.runIf(!!process.env.GEN_TEXTFX)("generate text-effects.gen.ts", () => {
  it("writes Word's text effect entries", () => {
    const file = readdirSync(RESULTS).filter((f) => f.endsWith("-word-texteffects.json")).sort().pop()!;
    const probe = JSON.parse(readFileSync(join(RESULTS, file), "utf-8")) as Record<string, { name: string; xml: string }[]> & { names: Record<string, string[]> };
    const presets = probe.presets.map((e) => {
      const xml = strip(e.xml);
      const color = /<w:color w:val="([^"]*)"((?: w:theme[A-Za-z]+="[^"]*")*)\/>/.exec(xml);
      const fx = ["glow", "shadow", "reflection", "textOutline", "textFill", "scene3d", "props3d"].map((n) => w14(xml, n) ?? "").join("");
      return { name: e.name, ...(color ? { color: color[1], colorTheme: color[2].trim() || undefined } : {}), fx };
    });
    const one = (list: { name: string; xml: string }[], el: string) => list.map((e) => ({ name: e.name, xml: w14(strip(e.xml), el) ?? null }));
    const src = `// Generated by packages/ooxml/test/gen-textfx.test.ts from Word's Texteffekte und Typografie
// (tools/feel-lab/probe_word_texteffects.py, ${file}). Do not edit.

/** The 15 presets (also Formformat > WordArt-Formate): font colour and w14 effects. */
export const TEXTFX_PRESETS: readonly { name: string; color?: string; colorTheme?: string; fx: string }[] = ${JSON.stringify(presets, null, 1)};

/** Schatten: Ohne, Außen (Offset), Innen, Perspektive. */
export const SHADOWS: readonly { name: string; xml: string | null }[] = ${JSON.stringify(one(probe.Schatten, "shadow"), null, 1)};

/** Spiegelung. */
export const REFLECTIONS: readonly { name: string; xml: string | null }[] = ${JSON.stringify(one(probe.Spiegelung, "reflection"), null, 1)};

/** Leuchten: 4 sizes × the 6 accent colours. */
export const GLOWS: readonly { name: string; xml: string | null }[] = ${JSON.stringify(one(probe.Leuchten, "glow"), null, 1)};

/** The other submenus' entries as Word names them. */
export const TEXTFX_NAMES: Readonly<Record<string, readonly string[]>> = ${JSON.stringify(probe.names, null, 1)};
`;
    writeFileSync(OUT, src.replace(/\r\n/g, "\n"), "utf-8");
    expect(presets.length).toBe(15);
  });
});
