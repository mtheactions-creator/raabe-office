export function applyTips(commands: Commands): void {
  for (const [id, t] of Object.entries(TIPS)) {
    if (!commands.has(id)) continue;
    const c = commands.get(id);
    c.tip = t.tip;
    if (t.shortcut !== undefined) c.shortcut = t.shortcut ?? undefined;
  }
}
