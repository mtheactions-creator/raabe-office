"""Generates apps/raabe-calc/src/timeline-styles.gen.ts from the 12 built-in Zeitachse styles as Excel reports them
through COM (probe_excel_timeline.py, packages/ooxml/test/fixtures/excel-timeline.json, D-121): per element the fill (a
gradient's first and last stop), the font colour, size and weight and the borders, theme colours kept as references.

    python tools/feel-lab/gen_timeline_styles.py
"""
from __future__ import annotations

import json
from pathlib import Path

from gen_slicer_styles import colour

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "packages" / "ooxml" / "test" / "fixtures" / "excel-timeline.json"
OUT = ROOT / "apps" / "raabe-calc" / "src" / "timeline-styles.gen.ts"
# XlTableStyleElementType of a timeline style's elements (the numbers Excel answered for).
ELEMENTS = {"0": "wholeTable", "1": "headerRow", "36": "selectionLabel", "37": "timeLevel", "38": "periodLabel1", "39": "periodLabel2",
            "40": "selectedTimeBlock", "41": "unselectedTimeBlock", "42": "selectedTimeBlockSpace"}


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))["styles"]
    styles = []
    for name, rec in data.items():
        els = {}
        for k, d in rec.items():
            if k not in ELEMENTS or not isinstance(d, dict):
                continue
            e: dict = {}
            if "gradient" in d:
                stops = d["gradient"]["stops"]
                e["fill"] = colour(stops[0])
                e["fill2"] = colour(stops[-1])
            elif d.get("fill"):
                e["fill"] = colour(d["fill"])
            f = d.get("font") or {}
            if f.get("colorIndex") not in (None, -4105):
                fc = colour(f)
                if fc:
                    e["font"] = fc
            if f.get("bold"):
                e["bold"] = True
            if f.get("size"):
                e["size"] = f["size"]
            b = {side: colour(v) for side, v in (d.get("borders") or {}).items()}
            if b:
                e["borders"] = b
            els[ELEMENTS[k]] = e
        styles.append({"name": name, "local": rec["local"], "elements": els})
    OUT.write_text(
        "// Generated by tools/feel-lab/gen_timeline_styles.py from Excel's built-in Zeitachse styles\n"
        "// (probe_excel_timeline.py, packages/ooxml/test/fixtures/excel-timeline.json, D-121). Do not edit.\n/* eslint-disable */\n\n"
        "import type { TsColor } from \"./table-styles.gen\";\n\n"
        "export interface TimelineElement { fill?: TsColor; fill2?: TsColor; font?: TsColor; bold?: boolean; size?: number; borders?: Record<string, TsColor> }\n"
        "export interface TimelineStyleDef { name: string; local: string; elements: Record<string, TimelineElement> }\n\n"
        "export const TIMELINE_STYLES: readonly TimelineStyleDef[] = " + json.dumps(styles, ensure_ascii=False) + ";\n",
        encoding="utf-8", newline="\n")
    print("written", OUT.name, len(styles))


if __name__ == "__main__":
    main()
