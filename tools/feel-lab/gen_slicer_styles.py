"""Generates apps/raabe-calc/src/slicer-styles.gen.ts from the 14 built-in Datenschnitt styles as Excel reports
them through COM (probe_excel_slicers.py, packages/ooxml/test/fixtures/excel-slicers.json, D-092): per element
the fill (a gradient's first and last stop), the font colour and weight and the borders, theme colours kept as
references (the workbook's design decides their RGB).

    python tools/feel-lab/gen_slicer_styles.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "packages" / "ooxml" / "test" / "fixtures" / "excel-slicers.json"
OUT = ROOT / "apps" / "raabe-calc" / "src" / "slicer-styles.gen.ts"
# COM's ThemeColor: 1 lt1, 2 dk1, 3 lt2, 4 dk2, 5..10 accents.
THEME = ["lt1", "dk1", "lt2", "dk2", "accent1", "accent2", "accent3", "accent4", "accent5", "accent6"]


def colour(c: dict | None):
    if not c or c.get("rgb") is None:
        return None
    t = c.get("theme")
    if isinstance(t, int) and 1 <= t <= 10:
        out = {"t": THEME[t - 1]}
        if c.get("tint"):
            out["tint"] = round(c["tint"], 6)
        return out
    return "#" + c["rgb"]


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))["styles"]
    styles = []
    for name, rec in data.items():
        if not rec:
            continue
        els = {}
        for el, d in rec.items():
            if el in ("local", "slicer") or not isinstance(d, dict):
                continue
            e: dict = {}
            if "gradient" in d:
                stops = d["gradient"]["stops"]
                e["fill"] = colour(stops[0])
                e["fill2"] = colour(stops[-1])
            elif d.get("fill"):
                e["fill"] = colour(d["fill"])
            f = d.get("font") or {}
            if f.get("colorIndex") not in (None, -4105):
                fc = colour(f)
                if fc:
                    e["font"] = fc
            if f.get("bold"):
                e["bold"] = True
            b = {side: colour(v) for side, v in (d.get("borders") or {}).items()}
            if b:
                e["borders"] = b
            els[el] = e
        styles.append({"name": name, "local": rec["local"], "elements": els})
    OUT.write_text(
        "// Generated by tools/feel-lab/gen_slicer_styles.py from Excel's built-in Datenschnitt styles\n"
        "// (probe_excel_slicers.py, packages/ooxml/test/fixtures/excel-slicers.json, D-092). Do not edit.\n/* eslint-disable */\n\n"
        "import type { TsColor } from \"./table-styles.gen\";\n\n"
        "export interface SlicerElement { fill?: TsColor; fill2?: TsColor; font?: TsColor; bold?: boolean; borders?: Record<string, TsColor> }\n"
        "export interface SlicerStyleDef { name: string; local: string; elements: Record<string, SlicerElement> }\n\n"
        "export const SLICER_STYLES: readonly SlicerStyleDef[] = " + json.dumps(styles, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8", newline="\n")
    print("written", OUT.name, len(styles))


if __name__ == "__main__":
    main()
