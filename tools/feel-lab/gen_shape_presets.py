"""Writes apps/raabe-write/src/features/shape-presets.ts from Word's recorded galleries of the
Formformat tab (captures/word-shapes-ui.json, probe_word_shapes_ui.py applylist): for each
Formenart the shape style (wps:style) and the shape properties it sets (fill, outline, without
transform and geometry), with Word's name (Office 2013-2022 theme, D-046).

    .venv/Scripts/python.exe gen_shape_presets.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parents[1]
OUT = ROOT / "apps/raabe-write/src/features/shape-presets.ts"
SRC = HERE / "captures" / "word-shapes-ui.json"


def parts(xml: str) -> tuple[str, str]:
    sp = re.search(r"<wps:spPr>(.*?)</wps:spPr>", xml, re.S)
    inner = sp.group(1) if sp else ""
    inner = re.sub(r"<a:xfrm[^>]*>.*?</a:xfrm>", "", inner, flags=re.S)
    inner = re.sub(r"<a:prstGeom[^>]*>.*?</a:prstGeom>", "", inner, flags=re.S)
    st = re.search(r"<wps:style>.*?</wps:style>", xml, re.S)
    return (st.group(0) if st else ""), inner


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    styles = data["applylist Formformat Formenarten Schnellformatvorlagen"]
    lines = [
        "// Generated by tools/feel-lab/gen_shape_presets.py from Word 365's Formenarten gallery",
        "// (probe_word_shapes_ui.py applylist, Office 2013-2022 theme). Each entry: the shape style",
        "// Word writes (wps:style) and what it sets in the shape properties (fill, outline).",
        "",
        "export interface ShapePreset { readonly label: string; readonly style: string; readonly spPr: string }",
        "",
        "/** Designformatvorlagen (42: six kinds × Dunkel 1 and Akzent 1–6), then Voreinstellungen (35). */",
        "export const SHAPE_STYLES: readonly ShapePreset[] = [",
    ]
    default = None
    for e in styles:
        xml = e.get("xml") or ""
        if not e.get("changed"):
            default = e["label"]
        st, sp = parts(xml)
        lines.append(f"  {{ label: {json.dumps(e['label'], ensure_ascii=False)}, style: {json.dumps(st)}, spPr: {json.dumps(sp)} }},")
    lines.append("];")
    lines.append("")
    lines.append(f"/** The entry that is Word's default shape style ({default}). */")
    lines.append(f"export const DEFAULT_SHAPE_STYLE_LABEL = {json.dumps(default, ensure_ascii=False)};")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT, len(styles))


if __name__ == "__main__":
    main()
