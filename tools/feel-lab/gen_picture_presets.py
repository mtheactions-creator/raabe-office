"""Writes apps/raabe-write/src/features/picture-presets.ts from Word's recorded Bildformat
galleries (results/<date>-word-picture.json, probe_word_picture.py): for every entry the
shape properties Word writes (geometry, fill, line, effects, 3D, without the transform), the
space its effects take, and Word's name from the tooltip where it was recorded.

    .venv/Scripts/python.exe gen_picture_presets.py results/2026-10-14-word-picture.json
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "apps/raabe-write/src/features/picture-presets.ts"

GROUPS = {
    "styles": "PICTURE_STYLES",
    "fx_preset": "EFFECT_PRESETS",
    "fx_shadow": "SHADOWS",
    "fx_reflection": "REFLECTIONS",
    "fx_glow": "GLOWS",
    "fx_soft": "SOFT_EDGES",
    "fx_bevel": "BEVELS",
    "fx_rot3d": "ROTATIONS_3D",
}


def fragment(sppr: str) -> str:
    inner = re.sub(r"^<pic:spPr[^>]*>|</pic:spPr>$", "", sppr)
    inner = re.sub(r"<a:xfrm[^>]*>.*?</a:xfrm>", "", inner, flags=re.S)
    return inner


def extent(xml: str) -> list[float] | None:
    m = re.search(r'l="(\d+)" t="(\d+)" r="(\d+)" b="(\d+)"', xml or "")
    if not m:
        return None
    v = [round(int(x) / 12700, 2) for x in m.groups()]
    return v if any(v) else None


def main() -> None:
    src = Path(sys.argv[1])
    data = json.loads(src.read_text(encoding="utf-8"))
    lines = [
        "// Generated by tools/feel-lab/gen_picture_presets.py from Word 365's Bildformat galleries",
        f"// ({src.name}). Each entry: the picture's shape properties as Word writes them (without",
        "// the transform), the room its effects take (wp:effectExtent, points), Word's name.",
        "",
        "export interface PicturePreset { readonly label: string; readonly xml: string; readonly extent?: readonly [number, number, number, number] }",
        "",
    ]
    for key, name in GROUPS.items():
        entries = data.get(key, [])
        tips = data.get(f"tips_{key}", {})
        items = []
        for e in entries:
            if not e.get("xml"):
                continue
            label = tips.get(e["label"], "") or e["label"]
            items.append({"label": label.split(" | ")[0], "id": e["label"], "xml": fragment(e["xml"]["spPr"]), "extent": extent(e["xml"].get("effectExtent", ""))})
        lines.append(f"export const {name}: readonly (PicturePreset & {{ readonly id: string }})[] = [")
        for it in items:
            ext = f", extent: [{', '.join(str(x) for x in it['extent'])}]" if it["extent"] else ""
            lines.append(f"  {{ id: {json.dumps(it['id'])}, label: {json.dumps(it['label'], ensure_ascii=False)}, xml: {json.dumps(it['xml'])}{ext} }},")
        lines.append("];")
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
