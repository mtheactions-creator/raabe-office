"""Entwurf > Farben and Schriftarten (D-070): Office's colour sets and font sets as data, from the files Office
installs on this PC (Document Themes 16\\Theme Colors and Theme Fonts), named as German PowerPoint names them
in its menus (results/2026-11-06-powerpoint-inventory.json). The new "Office" set (Aptos) comes from the
fixture PowerPoint built (pptx-office-blank.pptx).

    .venv/Scripts/python.exe gen_present_themesets.py

Writes apps/raabe-present/src/themesets.gen.ts.
"""
from __future__ import annotations

import json
import re
import zipfile
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
THEMES = Path(r"C:\Program Files\Microsoft Office\root\Document Themes 16")
OUT = ROOT / "apps" / "raabe-present" / "src" / "themesets.gen.ts"

# German menu names → the English file names Office ships (order as in PowerPoint's Farben menu).
COLORS = [("Office 2013 – 2022", "Office 2013 - 2022"), ("Office 2007 - 2010", "Office 2007 - 2010"), ("Graustufe", "Grayscale"), ("Warmes Blau", "Blue Warm"),
          ("Blau", "Blue"), ("Blau II", "Blue II"), ("Blaugrün", "Blue Green"), ("Grün", "Green"), ("Grüngelb", "Green Yellow"), ("Gelb", "Yellow"),
          ("Gelborange", "Yellow Orange"), ("Orange", "Orange"), ("Orangerot", "Orange Red"), ("Rotorange", "Red Orange"), ("Rot", "Red"), ("Rotviolett", "Red Violet"),
          ("Violett", "Violet"), ("Violett II", "Violet II"), ("Galathea", "Median"), ("Papier", "Paper"), ("Laufschrift", "Marquee"), ("Slipstream", "Slipstream"), ("Ganymed", "Aspect")]
NAMES = ["dk1", "lt1", "dk2", "lt2", "accent1", "accent2", "accent3", "accent4", "accent5", "accent6", "hlink", "folHlink"]


def scheme(xml: str) -> dict:
    out = {}
    for n in NAMES:
        m = re.search(rf"<a:{n}>\s*<a:(?:srgbClr val|sysClr val=\"\w+\" lastClr)=\"([0-9A-Fa-f]{{6}})\"", xml)
        out[n] = m.group(1).upper() if m else "000000"
    return out


def main() -> None:
    colors = []
    with zipfile.ZipFile(ROOT / "packages" / "ooxml" / "test" / "fixtures" / "pptx-office-blank.pptx") as z:
        colors.append({"name": "Office", "colors": scheme(z.read("ppt/theme/theme1.xml").decode("utf-8"))})
    for de, en in COLORS:
        f = THEMES / "Theme Colors" / f"{en}.xml"
        if f.exists():
            colors.append({"name": de, "colors": scheme(f.read_text(encoding="utf-8"))})
    inv = json.loads((HERE / "results" / "2026-11-06-powerpoint-inventory.json").read_text(encoding="utf-8"))
    labels = next(c for c in inv["tabs"]["Folie/Entwurf"]["controls"] if c["name"] == "Schriftarten")["items"]
    fonts = []
    seen = set()
    for it in labels:
        label = it["name"]
        if label in seen or label in ("Schriftarten", "Designschriftarten", "Alle Schriftarten") or label.startswith(("Zeile ", "Seite ", "Schriftarten anpassen")):
            continue
        seen.add(label)
        m = re.match(r"^(.*?), Überschriftenschriftart: (.*?), Textschriftart: (.*)$", label)
        if m:
            fonts.append({"label": label, "name": m.group(1), "major": m.group(2), "minor": m.group(3)})
            continue
        f = THEMES / "Theme Fonts" / f"{label}.xml"
        if f.exists():
            x = f.read_text(encoding="utf-8")
            maj = re.search(r"<a:majorFont>\s*<a:latin typeface=\"([^\"]*)\"", x).group(1)
            mnr = re.search(r"<a:minorFont>\s*<a:latin typeface=\"([^\"]*)\"", x).group(1)
            fonts.append({"label": label, "name": label, "major": maj, "minor": mnr})
    ts = ("// Generated by tools/feel-lab/gen_present_themesets.py from Office's colour and font sets (D-070). Do not edit.\n\n"
          f"export const COLOR_SETS: {{ name: string; colors: Record<string, string> }}[] = {json.dumps(colors, ensure_ascii=False)};\n\n"
          f"export const FONT_SETS: {{ label: string; name: string; major: string; minor: string }}[] = {json.dumps(fonts, ensure_ascii=False)};\n")
    OUT.write_text(ts, encoding="utf-8", newline="\n")
    print(len(colors), "colour sets,", len(fonts), "font sets ->", OUT)


if __name__ == "__main__":
    main()
