"""Generates apps/raabe-calc/src/table-styles.gen.ts from probe_excel_tablestyles.py's recording: every
built-in table style's elements with theme-relative colours (D-066).

    .venv/Scripts/python.exe gen_tablestyles.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parents[1]
THEME_INDEX = ["lt1", "dk1", "lt2", "dk2", "accent1", "accent2", "accent3", "accent4", "accent5", "accent6", "hlink", "folHlink"]


def color(c: dict) -> object:
    if "theme" in c:
        out: dict = {"t": THEME_INDEX[c["theme"] - 1]}
        if c.get("tint"):
            out["tint"] = c["tint"]
        return out
    return "#" + (c.get("rgb") or "000000")


def border_style(b: dict) -> str:
    ls, w = b.get("style"), b.get("weight")
    if ls == -4119:
        return "double"
    if ls == -4115:
        return "dashed"
    if ls == -4118:
        return "dotted"
    return {1: "hair", 2: "thin", -4138: "medium", 4: "thick"}.get(w, "thin")


def main() -> None:
    src = sorted((HERE / "results").glob("*-excel-tablestyles.json"))[-1]
    data = json.loads(src.read_text(encoding="utf-8"))
    styles = []
    for name, rec in data["styles"].items():
        els = {}
        for el, d in rec.items():
            if el == "local":
                continue
            e: dict = {}
            if "fill" in d:
                e["fill"] = color(d["fill"])
            if "font" in d:
                e["font"] = color(d["font"])
            if d.get("bold"):
                e["bold"] = True
            if "borders" in d:
                e["borders"] = {side: {"style": border_style(b), "color": color(b)} for side, b in d["borders"].items()}
            if "stripe" in d:
                e["stripe"] = d["stripe"]
            els[el] = e
        # "Tabellenformat - Mittel 2" -> group "Mittel", number 2 (the gallery's tooltip is the local name).
        styles.append({"name": name, "local": rec.get("local", name), "elements": els})
    body = json.dumps(styles, ensure_ascii=False, indent=1)
    out = ROOT / "apps" / "raabe-calc" / "src" / "table-styles.gen.ts"
    out.write_text(
        "// Generated by tools/feel-lab/gen_tablestyles.py from Excel's built-in table styles\n"
        f"// (probe_excel_tablestyles.py, {src.name}). Do not edit.\n/* eslint-disable */\n\n"
        "export type TsColor = string | { t: string; tint?: number };\n"
        "export interface TsElement { fill?: TsColor; font?: TsColor; bold?: boolean; borders?: Record<string, { style: string; color: TsColor }>; stripe?: number }\n"
        "export interface TableStyleDef { name: string; local: string; elements: Record<string, TsElement> }\n\n"
        f"export const DEFAULT_TABLE_STYLE = {json.dumps(data.get('default', 'TableStyleMedium2'))};\n\n"
        f"export const TABLE_STYLE_DEFS: readonly TableStyleDef[] = {body};\n",
        encoding="utf-8", newline="\n")
    print(len(styles), "styles ->", out.name)


if __name__ == "__main__":
    main()
