"""Generates packages/shell/src/office-designs.gen.ts, the Office designs, colour sets and font sets shared
by the apps (D-083), from what RaabeWrite and RaabePresent recorded:
- the designs (Entwurf > Designs in Word: names, colours, fonts) from apps/raabe-write/src/features/design-data.gen.ts,
- the colour and font sets (Office's own sets with their German names) from apps/raabe-present/src/themesets.gen.ts.

    python tools/feel-lab/gen_office_designs.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WRITE = ROOT / "apps/raabe-write/src/features/design-data.gen.ts"
PRESENT = ROOT / "apps/raabe-present/src/themesets.gen.ts"
OUT = ROOT / "packages/shell/src/office-designs.gen.ts"


def array_after(text: str, name: str) -> list:
    i = text.index(f"export const {name}")
    j = text.index("= [", i) + 2
    depth, k = 0, j
    in_str = False
    while True:
        c = text[k]
        if in_str:
            if c == "\\":
                k += 2
                continue
            if c == '"':
                in_str = False
        elif c == '"':
            in_str = True
        elif c == "[":
            depth += 1
        elif c == "]":
            depth -= 1
            if depth == 0:
                break
        k += 1
    return json.loads(text[j:k + 1])


def main() -> None:
    w = WRITE.read_text(encoding="utf-8")
    p = PRESENT.read_text(encoding="utf-8")
    themes = [{"name": t["name"], "colors": t["colors"], "major": t["major"], "minor": t["minor"]} for t in array_after(w, "THEMES")]
    colors = array_after(p, "COLOR_SETS")
    fonts = array_after(p, "FONT_SETS")
    body = (
        "// Generated by tools/feel-lab/gen_office_designs.py from RaabeWrite's recorded designs and RaabePresent's colour and\n"
        "// font sets (D-083). Do not edit.\n\n"
        "/** Seitenlayout/Entwurf > Designs: Office's designs (colours as RRGGBB, heading and body font). */\n"
        f"export const OFFICE_DESIGNS: readonly {{ name: string; colors: Readonly<Record<string, string>>; major: string; minor: string }}[] = {json.dumps(themes, ensure_ascii=False)};\n\n"
        "/** Farben: Office's colour sets with their German names. */\n"
        f"export const OFFICE_COLOR_SETS: readonly {{ name: string; colors: Readonly<Record<string, string>> }}[] = {json.dumps(colors, ensure_ascii=False)};\n\n"
        "/** Schriftarten: Office's font sets (label as the gallery's tooltip, heading and body font). */\n"
        f"export const OFFICE_FONT_SETS: readonly {{ label: string; name: string; major: string; minor: string }}[] = {json.dumps(fonts, ensure_ascii=False)};\n"
    )
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(len(themes), "designs,", len(colors), "colour sets,", len(fonts), "font sets")


if __name__ == "__main__":
    main()
