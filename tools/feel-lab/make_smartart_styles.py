"""SmartArt's colour sets and quick styles for RaabePresent (D-101): from PowerPoint's recording
(probe_powerpoint_smartart_styles.py) the parameters of the style labels our drawing uses (node1, sibTrans2D1,
parChTrans1D1, revTx, bgShp): colour lists with their method, and the quick styles' references to the theme's
fill, line and effect styles with their 3-D scene and shape. Writes apps/raabe-present/src/smartart-styles.gen.ts.

    .venv/Scripts/python.exe make_smartart_styles.py
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
OUT = ROOT / "apps/raabe-present/src/smartart-styles.gen.ts"
LABELS = ("node1", "sibTrans2D1", "parChTrans1D1", "revTx", "bgShp")


def main() -> None:
    src = sorted((HERE / "results").glob("*-powerpoint-smartart-styles.json"))[-1]
    d = json.loads(src.read_text(encoding="utf-8"))
    colors = [{"id": c["id"], "name": c["name"], "cat": c["category"], "labels": {k: v for k, v in c.get("labels", {}).items() if k in LABELS}}
              for c in d["colors"] if c.get("labels")]
    styles = [{"id": s["id"], "name": s["name"], "cat": s["category"], "camera": (s.get("scene") or {}).get("camera", "orthographicFront"),
               "labels": {k: v for k, v in s.get("labels", {}).items() if k in LABELS}} for s in d["styles"] if s.get("labels")]
    head = ("// Generated by tools/feel-lab/make_smartart_styles.py from PowerPoint's recording (" + src.name + "), D-101.\n"
            "// SmartArt-Design > Farben ändern and SmartArt-Formatvorlagen: per style label the colour lists (method, colours as\n"
            "// 'scheme or hex, then modifiers') and the quick styles' theme references, 3-D scene and shape. Do not edit.\n\n")
    body = ("export interface ClrList { meth: string; clr: string[]; hueDir?: string }\n"
            "export interface ColorLbl { fill?: ClrList; line?: ClrList; effect?: ClrList; txLine?: ClrList; txFill?: ClrList; txEffect?: ClrList }\n"
            "export interface ColorDef { id: string; name: string; cat: string; labels: Record<string, ColorLbl> }\n"
            "export interface StyleLbl { refs: { lnRef?: number; fillRef?: number; effectRef?: number }; font: string | null; camera?: string; cameraRot?: number[]; light?: string[]; sp3d?: Record<string, string | Record<string, string>> }\n"
            "export interface StyleDef { id: string; name: string; cat: string; camera: string; labels: Record<string, StyleLbl> }\n\n"
            f"export const SMARTART_COLORS: ColorDef[] = {json.dumps(colors, ensure_ascii=False)};\n\n"
            f"export const SMARTART_STYLES: StyleDef[] = {json.dumps(styles, ensure_ascii=False)};\n")
    OUT.write_text(head + body, encoding="utf-8", newline="\n")
    print(OUT.name, len(colors), "colour sets,", len(styles), "styles,", OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
