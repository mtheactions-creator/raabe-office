"""Entwurf > Varianten > Effekte as PowerPoint applies them (D-080, D-104). An invisible PowerPoint of our own (only
when no POWERPNT.EXE runs) loads each of Office's theme effect schemes into a new presentation of its own
(Theme.ThemeEffectScheme.Load, the files Office installs) and saves it; the effect scheme PowerPoint wrote into
the theme (a:fmtScheme) is read back. "Office" is the scheme of a new presentation's own theme. The German names
are PowerPoint's gallery entries (inventory), in its order, which is the order of the files below.

    .venv/Scripts/python.exe probe_powerpoint_theme_effects.py

Writes apps/raabe-present/src/themeeffects.gen.ts (name and a:fmtScheme per scheme) and
results/<date>-powerpoint-theme-effects.json (names and sizes).
"""
from __future__ import annotations

import datetime
import json
import re
import zipfile
from pathlib import Path

from feellab.powerpoint import PowerPointTarget

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
SRC = Path(r"C:\Program Files\Microsoft Office\root\Document Themes 16\Theme Effects")
CAP = HERE / "captures" / "theme-effects"
OUT = ROOT / "apps/raabe-present/src/themeeffects.gen.ts"
SCHEMES = [("Office", None), ("Office 2007 - 2010", "Office 2007 - 2010"), ("Subtile Körper", "Subtle Solids"), ("Verbundene Kante", "Banded Edge"),
           ("Rauchglas", "Smokey Glass"), ("Leuchteffekt: Rand", "Glow Edge"), ("Grunge-Muster", "Grunge Texture"), ("Mattiertes Glas", "Frosted Glass"),
           ("Schatten oben", "Top Shadow"), ("Abgesenkt", "Inset"), ("Milchglas", "Milk Glass"), ("Säule auf abgerundetem Sockel", "Riblet"),
           ("Spiegelung", "Reflection"), ("Extreme Schatten", "Extreme Shadow"), ("Glänzend", "Glossy")]


def main() -> None:
    CAP.mkdir(parents=True, exist_ok=True)
    out: dict = {"date": datetime.date.today().isoformat(), "schemes": []}
    gen = []
    t = PowerPointTarget(visible=False)
    try:
        for name, file in SCHEMES:
            pres = t.new_presentation(with_window=False, name="effects")
            if file:
                pres.SlideMaster.Theme.ThemeEffectScheme.Load(str(SRC / f"{file}.eftx"))
            path = CAP / f"{(file or 'Office').replace(' ', '-')}.pptx"
            t.save_copy(pres, path)
            pres.Saved = -1
            with zipfile.ZipFile(path) as z:
                theme = z.read("ppt/theme/theme1.xml").decode("utf-8")
            m = re.search(r"<a:fmtScheme\b.*?</a:fmtScheme>", theme, re.S)
            xml = m.group(0) if m else ""
            gen.append({"name": name, "xml": xml})
            out["schemes"].append({"name": name, "file": file, "bytes": len(xml)})
            print(name, len(xml), flush=True)
    finally:
        out["close"] = t.close(kill_if_unreachable=True)
    OUT.write_text("// Generated by tools/feel-lab/probe_powerpoint_theme_effects.py: Office's theme effect schemes as PowerPoint\n"
                   "// writes them into a theme (a:fmtScheme), by PowerPoint's German names (D-104). Do not edit.\n\n"
                   f"export const THEME_EFFECTS: {{ name: string; xml: string }}[] = {json.dumps(gen, ensure_ascii=False)};\n", encoding="utf-8", newline="\n")
    p = HERE / "results" / f"{out['date']}-powerpoint-theme-effects.json"
    p.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
