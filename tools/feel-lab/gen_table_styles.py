"""Generates apps/raabe-write/src/features/table-styles.gen.ts from Word's recordings (Step 4c D):
the Tabellenformatvorlagen gallery's 105 entries in Word's order and groups
(results/<date>-word-table-design.json) with each style's definition as Word writes it
(results/<date>-word-table-styles.json; colours keep their theme references, so RaabeWrite
can give them the document's theme colours).

    python gen_table_styles.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).parent
OUT = HERE.parents[1] / "apps" / "raabe-write" / "src" / "features" / "table-styles.gen.ts"


def latest(pattern: str) -> Path:
    return sorted((HERE / "results").glob(pattern))[-1]


def main() -> None:
    design = json.loads(latest("*-word-table-design.json").read_text(encoding="utf-8"))
    styles = json.loads(latest("*-word-table-styles.json").read_text(encoding="utf-8"))
    by_local = {v["local"]: (k, v) for k, v in styles.items()}
    rows = []
    for local in design["gallery"]:
        name, v = by_local[local]
        xml = v["xml"]
        # What does not change the look goes (revision ids).
        xml = re.sub(r"<w:rsid [^>]*/>", "", xml)
        rows.append({"name": name, "label": local, "id": v["id"], "xml": xml})
    assert len(rows) == 105, len(rows)
    lines = [
        "// Generated by tools/feel-lab/gen_table_styles.py from Word's recordings (2026-10-15). Do not edit.",
        "// Word's Tabellenformatvorlagen gallery: name, German label, style id and definition (w:style).",
        "",
        "export interface TableStylePreset { readonly name: string; readonly label: string; readonly id: string; readonly xml: string }",
        "",
        "/** The gallery's groups: heading and number of entries, in order. */",
        'export const TABLE_STYLE_GROUPS: readonly [string, number][] = [["Einfache Tabellen", 7], ["Rastertabellen", 49], ["Listentabellen", 49]];',
        "",
        "export const TABLE_STYLE_PRESETS: readonly TableStylePreset[] = [",
    ]
    for r in rows:
        lines.append("  " + json.dumps(r, ensure_ascii=False) + ",")
    lines.append("];")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(OUT, OUT.stat().st_size)


if __name__ == "__main__":
    main()
