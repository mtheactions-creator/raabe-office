"""Excel's inventory against RaabeCalc's (D-066): docs/EXCEL-INVENTORY.md with, per tab and group, every
control Excel has and whether RaabeCalc has it (vorhanden), has it greyed out as deferred
(zurückgestellt), lacks it (fehlt) or leaves it out on purpose (Cloud). Menus are compared entry by
entry. Labels only (D-058).

    .venv/Scripts/python.exe inventory_report.py [excel-inventory.json] [raabe-inventory.json]

RaabeCalc's side comes from the app (`__calc.inventory()`), saved by `inventory_calc.py`.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parent.parent


def norm(s: str) -> str:
    s = s.replace("…", "...").strip()
    s = re.sub(r"\s*\(Strg\+[^)]*\)$", "", s)
    s = re.sub(r"\.\.\.$", "", s).strip()
    return s.lower()


def latest(pattern: str) -> Path:
    files = sorted((HERE / "results").glob(pattern))
    if not files:
        raise SystemExit(f"no {pattern}")
    return files[-1]


def flatten_raabe(tabs: list[dict]) -> dict[str, dict]:
    """tab name -> {control name -> item} with menu entries as name -> item."""
    out: dict[str, dict] = {}
    for t in tabs:
        ctl: dict[str, dict] = {}
        for g in t["groups"]:
            if g.get("launcher"):
                ctl.setdefault(norm(g["launcher"]["name"]), g["launcher"])
            for c in g["controls"]:
                ctl.setdefault(norm(c["name"]), c)
        out[t["name"]] = ctl
    return out


def entries(items: list[dict] | None) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for it in items or []:
        out.setdefault(norm(it["name"]), it)
        for s in it.get("submenu", []) or []:
            out.setdefault(norm(s["name"]), s)
    return out


def status(rc: dict | None) -> str:
    if rc is None:
        return "fehlt"
    if rc.get("deferred"):
        return "zurückgestellt"
    return "vorhanden"


def main() -> None:
    xl = json.loads((Path(sys.argv[1]) if len(sys.argv) > 1 else latest("*-excel-inventory.json")).read_text(encoding="utf-8"))
    rc = json.loads((Path(sys.argv[2]) if len(sys.argv) > 2 else latest("*-raabe-inventory.json")).read_text(encoding="utf-8"))
    raabe = flatten_raabe(rc)
    counts = {"vorhanden": 0, "zurückgestellt": 0, "fehlt": 0, "Cloud": 0}
    lines: list[str] = []
    for key, tab in xl["tabs"].items():
        ctx, name = key.split("/", 1)
        mine = raabe.get(name, {})
        lines.append(f"\n## {name}" + (f" (bei {ctx})" if ctx != "Blatt" else "") + "\n")
        lines.append("| Gruppe | Steuerelement | RaabeCalc | Menüeinträge vorhanden |")
        lines.append("|---|---|---|---|")
        for c in tab["controls"]:
            if c.get("cloud"):
                st = "Cloud"
            else:
                st = status(mine.get(norm(c["name"])))
            counts[st] += 1
            menu = ""
            if c.get("items"):
                ex = entries(c["items"])
                own = mine.get(norm(c["name"]), {})
                have = entries(own.get("items"))
                if own.get("panel"):
                    # RaabeCalc draws this control's entries in its own panel (palette, gallery).
                    have = {k: {} for k in ex}
                hit = sum(1 for k in ex if k in have and not have[k].get("deferred"))
                menu = f"{hit}/{len(ex)}"
                for k, it in ex.items():
                    s = "vorhanden" if k in have and not have[k].get("deferred") else "fehlt"
                    counts[s] += 1
            lines.append(f"| {c.get('group', '')} | {c['name']} | {st} | {menu} |")
    total = sum(v for k, v in counts.items() if k != "Cloud")
    head = [
        "# Excel's inventory against RaabeCalc",
        "",
        "Generated by `tools/feel-lab/inventory_report.py` from Excel's own ribbon, menus and dialogs",
        "(`probe_excel_inventory.py`) and RaabeCalc's ribbon (D-066). Labels only. Entries of RaabeCalc's own",
        "panels (colour palettes, galleries) count as present; contextual tabs RaabeCalc lacks count as missing.",
        "",
        f"**Coverage:** {counts['vorhanden']} of {total} controls and menu entries are in RaabeCalc "
        f"({100 * counts['vorhanden'] / max(1, total):.1f} %); {counts['zurückgestellt']} are there but greyed out as deferred, "
        f"{counts['fehlt']} are missing; {counts['Cloud']} cloud features are left out on purpose.",
        "",
        f"Dialogs recorded in Excel: {len(xl.get('dialogs', {}))}.",
    ]
    out = ROOT / "docs" / "EXCEL-INVENTORY.md"
    out.write_text("\n".join(head + lines) + "\n", encoding="utf-8", newline="\n")
    print(counts, f"-> {out}")


if __name__ == "__main__":
    main()
