"""Zellenabschrägung as PowerPoint draws it (D-103): from PowerPoint's picture of the bevel table
(check_present_cellbevel.py --record, captures/cellbevel/powerpoint.png) the brightness across each edge of each
of the twelve bevels, in eight steps over the bevel's width, as a blend of the cell's face colour towards white
(positive) or black (negative), and how much the face itself is darkened. Writes
apps/raabe-present/src/render/cellbevel.gen.ts.

    .venv/Scripts/python.exe make_cellbevel_profiles.py
"""
from __future__ import annotations

import json
from pathlib import Path

from PIL import Image

from check_present_cellbevel import BEVELS, BOX, PRST

HERE = Path(__file__).parent
ROOT = HERE.parent.parent
OUT = ROOT / "apps/raabe-present/src/render/cellbevel.gen.ts"
STEPS = 8
WIDTH_PT = 6.0  # the bevel's default width (76200 EMU)


def lum(p) -> float:
    return (p[0] + p[1] + p[2]) / 3


def main() -> None:
    im = Image.open(HERE / "captures" / "cellbevel" / "powerpoint.png").convert("RGB")
    s = im.width / 960
    cw, ch = BOX[2] / 4, BOX[3] / 3
    profiles: dict = {}
    for k, b in enumerate(BEVELS):
        r, c = divmod(k, 4)
        x0, y0 = BOX[0] + c * cw, BOX[1] + r * ch
        x1, y1 = x0 + cw, y0 + ch
        face = lum(im.getpixel((int((x0 + cw * 0.6) * s), int((y0 + ch * 0.6) * s))))

        def blend(v: float) -> float:
            return round((v - face) / (255 - face) if v >= face else (v - face) / max(face, 1), 3)

        def edge(px, py) -> list[float]:
            out = []
            for i in range(STEPS):
                d = (i + 0.5) / STEPS * WIDTH_PT
                vals = [lum(im.getpixel((int(px(d, f) * s), int(py(d, f) * s)))) for f in (0.45, 0.55, 0.65, 0.75)]
                out.append(blend(sum(vals) / len(vals)))
            return out
        profiles[PRST[b]] = {
            "left": edge(lambda d, f: x0 + d, lambda d, f: y0 + ch * f),
            "right": edge(lambda d, f: x1 - d, lambda d, f: y0 + ch * f),
            "top": edge(lambda d, f: x0 + cw * f, lambda d, f: y0 + d),
            "bottom": edge(lambda d, f: x0 + cw * f, lambda d, f: y1 - d),
        }
    head = ("// Generated by tools/feel-lab/make_cellbevel_profiles.py from PowerPoint's picture of the twelve cell bevels (D-103).\n"
            "// Per bevel and edge: eight steps over the bevel's width from the edge inwards, each the face colour blended\n"
            "// towards white (positive share) or black (negative share). Do not edit.\n\n")
    body = (f"export const CELL_BEVEL_PROFILES: Record<string, Record<\"left\" | \"right\" | \"top\" | \"bottom\", number[]>> = {json.dumps(profiles)};\n")
    OUT.write_text(head + body, encoding="utf-8", newline="\n")
    print(json.dumps({k: v["left"][:3] + v["right"][:3] for k, v in profiles.items()}))


if __name__ == "__main__":
    main()
