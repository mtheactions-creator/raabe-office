"""Generates apps/raabe-write/src/features/languages.gen.ts: every language Word lists in the
dialog Sprache (names as Word shows them, recorded by probe_word_languages.py) with the tag
Word writes into w:lang (from Windows' LCIDToLocaleName).

    python gen_languages.py
"""
from __future__ import annotations

import ctypes
import json
from pathlib import Path

HERE = Path(__file__).parent
ROOT = HERE.parents[1]
SRC = sorted((HERE / "results").glob("*-word-languages.json"))[-1]
OUT = ROOT / "apps" / "raabe-write" / "src" / "features" / "languages.gen.ts"


def tag(lcid: int) -> str:
    buf = ctypes.create_unicode_buffer(85)
    n = ctypes.windll.kernel32.LCIDToLocaleName(lcid, buf, 85, 0x08000000)  # LOCALE_ALLOW_NEUTRAL_NAMES
    return buf.value if n else ""


def main() -> None:
    data = json.loads(SRC.read_text(encoding="utf-8"))
    langs = []
    for entry in data["com"]["languages"]:
        if entry["id"] == 1024:  # (Keine Überprüfung)
            continue
        # 4096 is Windows' "custom" id; Word's Schweizerdeutsch writes gsw-CH.
        t = "gsw-CH" if entry["id"] == 4096 else tag(entry["id"])
        if t:
            langs.append((t, entry["name"]))
    fold = str.maketrans("ÄÖÜäöüß", "AOUaous")
    langs.sort(key=lambda x: x[1].translate(fold).lower())
    lines = ",\n".join(f"  [{json.dumps(t)}, {json.dumps(n, ensure_ascii=False)}]" for t, n in langs)
    OUT.write_text(f"""// Generated by tools/feel-lab/gen_languages.py from {SRC.name}: the languages of Word's dialog
// Sprache (Word's names) with the tag Word writes into w:lang.

export const LANGUAGES: readonly (readonly [tag: string, name: string])[] = [
{lines},
];
""", encoding="utf-8", newline="\n")
    print(len(langs), "languages")


if __name__ == "__main__":
    main()
