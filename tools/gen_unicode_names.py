"""Generates apps/raabe-write/src/features/unicode-names.gen.ts: the Unicode character names
Word's Symbol dialog shows ("Euro Sign"), for the characters fonts on a school PC have (the
BMP without CJK ideographs, Hangul syllables and private use; math letters; emoji). Names are
stored compactly: a word list and, per character, word indices. Loaded only when the dialog
opens. Uses Python's unicodedata (Unicode 16 in Python 3.14).

    python tools/gen_unicode_names.py
"""
from __future__ import annotations

import json
import unicodedata
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "apps" / "raabe-write" / "src" / "features" / "unicode-names.gen.ts"

SKIP = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xAC00, 0xD7A3), (0xD800, 0xF8FF), (0xF900, 0xFAFF)]
EXTRA = [(0x1D400, 0x1D7FF), (0x1F300, 0x1FAFF), (0x2600, 0x27BF)]


def wanted(cp: int) -> bool:
    return not any(a <= cp <= b for a, b in SKIP)


def main() -> None:
    names: dict[int, str] = {}
    for cp in list(range(0x20, 0x10000)) + [c for a, b in EXTRA for c in range(a, b + 1)]:
        if not wanted(cp):
            continue
        n = unicodedata.name(chr(cp), "")
        if n:
            names[cp] = n
    # Words by frequency: the most common get the shortest indices.
    freq: dict[str, int] = {}
    for n in names.values():
        for w in n.split(" "):
            freq[w] = freq.get(w, 0) + 1
    words = sorted(freq, key=lambda w: (-freq[w], w))
    index = {w: i for i, w in enumerate(words)}
    # Runs of consecutive code points: [start, [name as word indices] …].
    runs: list[list] = []
    prev = None
    for cp in sorted(names):
        enc = [index[w] for w in names[cp].split(" ")]
        if prev is not None and cp == prev + 1:
            runs[-1][1].append(enc)
        else:
            runs.append([cp, [enc]])
        prev = cp
    body = json.dumps({"w": words, "r": runs}, separators=(",", ":"))
    OUT.write_text(
        "// Generated by tools/gen_unicode_names.py from Unicode's character names. Do not edit.\n"
        f"export const NAMES = {body};\n",
        encoding="utf-8", newline="\n")
    print(len(names), "names,", len(words), "words,", OUT.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
